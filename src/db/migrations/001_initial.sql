-- ============================================================================
-- js-chatbot-assistant — complete schema, single file.
--
-- Generated with `pg_dump` from a fully-migrated database, so it is the CURRENT
-- state of the whole schema rather than an ordered set of patches.
--
-- Install:  set DB_SCHEMA / DB_USER / DB_MIGRATOR_USER in .env, create the
-- database, role and the pgvector extension (see README), then run
-- `npm run migrate`.
--
-- `{{schema}}` is replaced with the double-quoted DB_SCHEMA value by
-- src/db/migrate.ts (renderSchema), so the schema name is a deployment choice
-- and is NOT hardcoded here. There are no role names in this file either:
-- objects are created by the role that runs the migration, which owns whatever
-- it creates, and src/db/migrate.ts grants the app role its privileges
-- afterwards (grantAppPrivileges).
--
-- Requires the pgvector `vector` type. `CREATE EXTENSION` is here because
-- pg_dump never dumps extensions, but document_chunks.embedding is typed
-- {{schema}}.vector. NOTE: pgvector is NOT a "trusted" extension, so this one
-- statement needs a PostgreSQL superuser — every other statement runs as
-- DB_MIGRATOR_USER. On Supabase (and similar) the extension is usually already
-- enabled, and `IF NOT EXISTS` makes this a no-op.
--
-- Deliberate deviations from raw pg_dump output:
--   * Idempotency guards, so re-running is safe: IF NOT EXISTS on schema,
--     tables and indexes, OR REPLACE on the function. pg_dump emits bare
--     CREATE statements, which abort on a re-run.
--   * Identity columns are declared inline instead of via pg_dump's trailing
--     `ALTER TABLE ... ADD GENERATED ... AS IDENTITY`, which errors on a table
--     that already has the identity.
--   * Role-specific statements were removed (see above): 23 `ALTER ... OWNER
--     TO <role>` and 41 `GRANT ... TO <app_role>` blocks, including one
--     `GRANT ALL ON SCHEMA` that would have handed the app role CREATE.
--   * `schema_migrations` is absent by design. It is created by the migration
--     runner itself (migrate.ts ensureMigrationsTable) before this file runs; a
--     pg_dump of a live database picks it up, and including it added a second
--     primary key (42P16 "multiple primary keys ... are not allowed").
--
-- The remaining `ALTER TABLE ... ADD CONSTRAINT` and `CREATE POLICY` statements
-- are non-idempotent by nature. They do not need to be: the runner records
-- applied files in <schema>.schema_migrations and skips them, and its
-- reconciliation path tolerates the duplicate-object error codes.
-- ============================================================================

